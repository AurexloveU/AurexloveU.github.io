    '用一种食物形容今天的心情。',
    '今天你在哪个瞬间感到平静?',
    '写一写今天路上遇到的一个陌生人。',
    '如果今天可以重来一次,你会改动哪个决定?',
    '今天有什么事,是你独自完成、无人知晓的?',
    '写下此刻最想去的一个地方,以及想在那里做的事。',
    '今天的疲惫来自哪里?温柔地拆解它。',
    '有没有一首歌适合做今天的背景音?为什么是它?',
