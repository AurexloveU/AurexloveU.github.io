let n = 0;
for (const [gtags, requireAny, forbid, defs] of GROUPS) {
  for (const d of defs) {
    n += 1;
    items.push({
      id: `p-${String(n).padStart(3, '0')}`,
      name: d[0], en: d[1], desc: d[2],
      category: 'place',
      tags: gtags.concat(d[3] || []),
      requireAll: [],
      requireAny,
      forbid,
    });
  }
}

